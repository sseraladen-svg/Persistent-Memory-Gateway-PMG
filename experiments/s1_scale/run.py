"""S1: does the product's retrieval cost stay flat as the store grows?   python experiments/s1_scale/run.py

Criteria fixed before the first run (goal 14, cost independent of store size):
  1. median and p95 `Memory.retrieve` latency at N = 100,000 are at most 50 ms;
  2. median latency grows by at most 3x from N = 10,000 to N = 100,000 (10x more data);
  3. tokens injected per query stay within the budget at every N.
Measured on the real `pmg.store.Memory` (SQLite FTS5 + the real ranking code), one core, same machine, synthetic text
from the E1 gym (Zipf word frequencies), 300 queries per size. Bulk loading bypasses `add()` for speed but writes the
same tables. Pass or fail is reported either way.
"""
from __future__ import annotations

import json
import os
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.append(str(HERE.parents[1] / "experiments" / "e1_topology_router"))

from gym import make_gym  # noqa: E402

SIZES = (1_000, 10_000, 100_000)


def build(db_dir: str, n: int):
    os.environ["PMG_DATA"] = db_dir
    from pmg.store import Memory
    from pmg.textutil import normalize, unique_keywords

    gym = make_gym(501, n_topics=n // 50, per_topic=50, n_queries=300)
    m = Memory()
    now = time.time()
    with m._db() as c:
        for ch in gym.chunks:
            tags = " ".join(unique_keywords(ch.text, 6))
            cur = c.execute("INSERT INTO chunks (kind,text,norm,tags,created_at,updated_at) VALUES ('fact',?,?,?,?,?)",
                            (ch.text, normalize(ch.text), tags, now, now))
            c.execute("INSERT INTO chunks_fts(rowid,text,tags) VALUES (?,?,?)", (cur.lastrowid, ch.text, tags))
    return m, gym


def measure(m, gym):
    for q in gym.queries[:20]:
        m.retrieve(q.text, log=False)
    times, tokens, nchunks = [], [], []
    for q in gym.queries:
        t = time.perf_counter()
        r = m.retrieve(q.text, log=False)
        times.append((time.perf_counter() - t) * 1000)
        tokens.append(r["tokens"])
        nchunks.append(len(r["chunks"]))
    times.sort()
    return {"median_ms": statistics.median(times), "p95_ms": times[int(0.95 * (len(times) - 1))],
            "max_tokens": max(tokens), "mean_tokens": statistics.mean(tokens), "mean_chunks": statistics.mean(nchunks)}


def main():
    out = {}
    for n in SIZES:
        with tempfile.TemporaryDirectory(prefix="pmg-scale-") as d:
            t = time.perf_counter()
            m, gym = build(d, n)
            load_s = time.perf_counter() - t
            r = measure(m, gym)
            r["load_seconds"] = load_s
            r["db_mb"] = Path(m.db_path).stat().st_size / 1e6
            from pmg import rules
            r["budget"] = rules.load()["budget_tokens"]
            out[n] = r
            print(n, json.dumps(r), flush=True)
    big, mid = out[100_000], out[10_000]
    checks = {
        "latency_le_50ms_at_100k": big["median_ms"] <= 50 and big["p95_ms"] <= 50,
        "growth_le_3x_from_10k_to_100k": big["median_ms"] <= 3 * mid["median_ms"],
        "tokens_within_budget": all(r["max_tokens"] <= r["budget"] for r in out.values()),
    }
    rep = {"sizes": out, "checks": checks, "pass": all(checks.values())}
    (HERE / "results.json").write_text(json.dumps(rep, indent=1))
    L = ["# S1 results (retrieval cost vs store size)", "",
         "Generated by `run.py`. Criteria were fixed before the first run (see the file header). Synthetic text; real "
         "`Memory.retrieve` on SQLite FTS5.", "", f"## Verdict: **{'PASS' if rep['pass'] else 'FAIL'}**", ""]
    L += [f"- {'pass' if ok else 'FAIL'}: {k}" for k, ok in checks.items()]
    L += ["", "| Chunks | Median ms | p95 ms | Mean tokens injected | Max tokens | DB size MB | Load time s |", "|---|---|---|---|---|---|---|"]
    for n, r in out.items():
        L.append(f"| {n:,} | {r['median_ms']:.2f} | {r['p95_ms']:.2f} | {r['mean_tokens']:.0f} | {r['max_tokens']} | {r['db_mb']:.1f} | {r['load_seconds']:.1f} |")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
