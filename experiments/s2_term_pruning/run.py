"""Run S2 exactly as written in PROTOCOL.md.   python experiments/s2_term_pruning/run.py"""
from __future__ import annotations

import json
import os
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.append(str(HERE.parents[1] / "experiments" / "e1_topology_router"))

from gym import make_gym  # noqa: E402

SIZES = (1_000, 10_000, 100_000)
SEED = 601
TESTED_COMMON_DF = 2000  # the single threshold fixed in PROTOCOL.md


def build(db_dir: str, n: int):
    os.environ["PMG_DATA"] = db_dir
    from pmg.store import Memory
    from pmg.textutil import normalize, unique_keywords

    gym = make_gym(SEED, n_topics=n // 50, per_topic=50, n_queries=300)
    m = Memory()
    now = time.time()
    with m._db() as c:
        for ch in gym.chunks:
            tags = " ".join(unique_keywords(ch.text, 6))
            cur = c.execute("INSERT INTO chunks (kind,text,norm,tags,created_at,updated_at) VALUES ('fact',?,?,?,?,?)",
                            (ch.text, normalize(ch.text), tags, now, now))
            c.execute("INSERT INTO chunks_fts(rowid,text,tags) VALUES (?,?,?)", (cur.lastrowid, ch.text, tags))
    return m, gym


def measure(m, gym, common_df):
    m.common_df = common_df
    m._common_cache.clear()
    for q in gym.queries[:20]:
        m.retrieve(q.text, log=False)
    times, tokens, by_group = [], [], {}
    d_tokens = []
    for q in gym.queries:
        t = time.perf_counter()
        r = m.retrieve(q.text, log=False)
        times.append((time.perf_counter() - t) * 1000)
        tokens.append(r["tokens"])
        got = {c["id"] for c in r["chunks"]}
        if q.kind == "D":
            d_tokens.append(r["tokens"])
        else:
            by_group.setdefault(q.group, []).append(sum((n + 1) in got for n in q.needed) / len(q.needed))
    times.sort()
    return {"median_ms": statistics.median(times), "p95_ms": times[int(0.95 * (len(times) - 1))],
            "macro_recall": statistics.mean(statistics.mean(v) for v in by_group.values()),
            "mean_tokens": statistics.mean(tokens), "max_tokens": max(tokens),
            "mean_tokens_vague": statistics.mean(d_tokens)}


def main():
    from pmg import rules

    out = {}
    for n in SIZES:
        with tempfile.TemporaryDirectory(prefix="pmg-s2-") as d:
            m, gym = build(d, n)
            budget = rules.load()["budget_tokens"]
            out[n] = {"off": measure(m, gym, 0), "on": measure(m, gym, TESTED_COMMON_DF), "budget": budget}
            print(n, json.dumps(out[n]), flush=True)
    big, mid = out[100_000]["on"], out[10_000]["on"]
    checks = {
        "latency_le_50ms_at_100k": big["median_ms"] <= 50 and big["p95_ms"] <= 50,
        "growth_le_3x_from_10k_to_100k": big["median_ms"] <= 3 * mid["median_ms"],
        "recall_within_0.01_at_every_N": all(r["on"]["macro_recall"] >= r["off"]["macro_recall"] - 0.01 for r in out.values()),
        "tokens_within_budget": all(r["on"]["max_tokens"] <= r["budget"] for r in out.values()),
    }
    rep = {"sizes": out, "checks": checks, "pass": all(checks.values())}
    (HERE / "results.json").write_text(json.dumps(rep, indent=1))
    L = ["# S2 results (dropping very common query words)", "",
         "Generated by `run.py`. Rules in `PROTOCOL.md` were fixed before the change was measured. Synthetic text, seed "
         f"{SEED}, real `Memory.retrieve`. \"off\" and \"on\" differ only in word pruning (both use synchronous=NORMAL).", "",
         f"## Verdict: **{'PASS' if rep['pass'] else 'FAIL'}**", ""]
    L += [f"- {'pass' if ok else 'FAIL'}: {k}" for k, ok in checks.items()]
    L += ["", "| Chunks | Pruning | Median ms | p95 ms | Macro recall | Mean tokens | Mean tokens (vague) |", "|---|---|---|---|---|---|---|"]
    for n, r in out.items():
        for k in ("off", "on"):
            x = r[k]
            L.append(f"| {n:,} | {k} | {x['median_ms']:.2f} | {x['p95_ms']:.2f} | {x['macro_recall']:.3f} | {x['mean_tokens']:.0f} | {x['mean_tokens_vague']:.0f} |")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
