"""Run S3 as written in PROTOCOL.md.

    python experiments/s3_hot_path/run.py measure --src <dir containing pmg/> --label baseline|new
    python experiments/s3_hot_path/run.py compare
"""
from __future__ import annotations

import argparse
import json
import os
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SIZES = (1_000, 10_000, 100_000)
SEED = 801
TESTED_COMMON_DF = 2000


def measure(src: str, label: str) -> dict:
    sys.path.insert(0, src)
    sys.path.append(str(REPO / "experiments" / "e1_topology_router"))
    from gym import make_gym
    import pmg
    from pmg import rules
    from pmg.store import Memory
    from pmg.textutil import normalize, unique_keywords

    assert str(Path(pmg.__file__).resolve()).startswith(str(Path(src).resolve())), "imported pmg from the wrong tree"
    out = {}
    for n in SIZES:
        with tempfile.TemporaryDirectory(prefix="pmg-s3-") as d:
            os.environ["PMG_DATA"] = d
            gym = make_gym(SEED, n_topics=n // 50, per_topic=50, n_queries=300)
            m = Memory()
            now = time.time()
            with m._db() as c:
                for ch in gym.chunks:
                    cur = c.execute("INSERT INTO chunks (kind,text,norm,tags,created_at,updated_at) VALUES ('fact',?,?,?,?,?)",
                                    (ch.text, normalize(ch.text), " ".join(unique_keywords(ch.text, 6)), now, now))
                    c.execute("INSERT INTO chunks_fts(rowid,text,tags) VALUES (?,?,?)", (cur.lastrowid, ch.text, ""))
            if label == "new":  # "new_nopruning" is a descriptive ablation: same code, pruning left off
                m.common_df = TESTED_COMMON_DF
            for q in gym.queries[:20]:
                m.retrieve(q.text, log=True)
            times, tokens, groups = [], [], {}
            for q in gym.queries:
                t = time.perf_counter()
                r = m.retrieve(q.text, log=True)
                times.append((time.perf_counter() - t) * 1000)
                tokens.append(r["tokens"])
                got = {c["id"] for c in r["chunks"]}
                if q.kind != "D":
                    groups.setdefault(q.group, []).append(sum((i + 1) in got for i in q.needed) / len(q.needed))
            if hasattr(m, "flush"):
                m.flush()
            with m._db() as c:
                n_events = c.execute("SELECT COUNT(*) FROM events").fetchone()[0]
                recount = c.execute("SELECT COALESCE(SUM(MAX(1, LENGTH(text) / 4) + 2), 0) FROM chunks").fetchone()[0]
                try:
                    running = c.execute("SELECT value FROM meta WHERE key = 'stored_tokens'").fetchone()[0]
                except Exception:
                    running = None
            times.sort()
            out[n] = {"median_ms": statistics.median(times), "p95_ms": times[int(0.95 * (len(times) - 1))],
                      "macro_recall": statistics.mean(statistics.mean(v) for v in groups.values()),
                      "mean_tokens": statistics.mean(tokens), "max_tokens": max(tokens),
                      "budget": rules.load()["budget_tokens"], "events": n_events, "requests": 320,
                      "total_correct": None if running is None else running == recount}
            print(label, n, json.dumps(out[n]), flush=True)
    (HERE / f"results_{label}.json").write_text(json.dumps(out, indent=1))
    return out


def compare() -> None:
    base = json.loads((HERE / "results_baseline.json").read_text())
    new = json.loads((HERE / "results_new.json").read_text())
    big, mid = new[str(100_000)], new[str(10_000)]
    checks = {
        "latency_le_50ms_at_100k": big["median_ms"] <= 50 and big["p95_ms"] <= 50,
        "growth_le_3x_from_10k_to_100k": big["median_ms"] <= 3 * mid["median_ms"],
        "recall_within_0.01_of_baseline_at_every_N": all(new[k]["macro_recall"] >= base[k]["macro_recall"] - 0.01 for k in new),
        "tokens_within_budget_and_total_correct": all(v["max_tokens"] <= v["budget"] and v["total_correct"] for v in new.values()),
        "no_events_lost": all(v["events"] == v["requests"] for v in new.values()),
    }
    ok = all(checks.values())
    L = ["# S3 results (the real request path, log=True)", "",
         f"Generated by `run.py compare`. Rules in `PROTOCOL.md` were fixed before the changes were implemented. Synthetic text, "
         f"seed {SEED}. Baseline is commit a5f6b2e as shipped; new is the working tree with pruning at {TESTED_COMMON_DF}.", "",
         f"## Verdict: **{'PASS' if ok else 'FAIL'}**", ""]
    L += [f"- {'pass' if v else 'FAIL'}: {k}" for k, v in checks.items()]
    L += ["", "| Chunks | Tree | Median ms | p95 ms | Macro recall | Mean tokens | Events written / requests |", "|---|---|---|---|---|---|---|"]
    for k in new:
        for label, d in (("baseline", base), ("new", new)):
            x = d[k]
            L.append(f"| {int(k):,} | {label} | {x['median_ms']:.2f} | {x['p95_ms']:.2f} | {x['macro_recall']:.3f} | "
                     f"{x['mean_tokens']:.0f} | {x['events']} / {x['requests']} |")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    json.dump({"pass": ok, "checks": checks}, open(HERE / "verdict.json", "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["measure", "compare"])
    ap.add_argument("--src")
    ap.add_argument("--label")
    a = ap.parse_args()
    measure(a.src, a.label) if a.mode == "measure" else compare()
