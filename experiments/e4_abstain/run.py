"""Run E4 as written in PROTOCOL.md.   python experiments/e4_abstain/run.py"""
from __future__ import annotations

import json
import os
import random
import statistics
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))
sys.path.append(str(HERE.parents[1] / "experiments" / "e1_topology_router"))

from gym import N_COMMON, TOPIC_WORDS, make_gym  # noqa: E402

SEED, N_TOPICS = 1001, 200
SETTINGS = {"baseline": None, "(0.01, 5)": (0.01, 5), "(0.01, 50)": (0.01, 50)}


def short_questions(gym, n=150):
    """Type E: exactly one topic word plus 0-2 common words; needs the topic's three key chunks."""
    rng = random.Random(SEED + 1)
    zipf = lambda k: [1.0 / (i + 1) for i in range(k)]
    keys = {}
    for c in gym.chunks:
        if c.key:
            keys.setdefault(c.topic, []).append(c.id)
    out = []
    for i in range(n):
        t = rng.randrange(N_TOPICS)
        words = rng.choices([f"t{t:02d}w{j:02d}" for j in range(TOPIC_WORDS)], weights=zipf(TOPIC_WORDS), k=1)
        words += rng.choices([f"c{j:03d}" for j in range(N_COMMON)], weights=zipf(N_COMMON), k=rng.choice((0, 1, 2)))
        rng.shuffle(words)
        out.append((" ".join(words), tuple(keys[t])))
    return out


def main():
    from pmg.store import Memory
    from pmg.textutil import normalize, unique_keywords

    gym = make_gym(SEED, n_topics=N_TOPICS, per_topic=50, n_queries=300)
    shorts = short_questions(gym)
    with tempfile.TemporaryDirectory(prefix="pmg-e4-") as d:
        os.environ["PMG_DATA"] = d
        m = Memory()
        now = time.time()
        with m._db() as c:
            for ch in gym.chunks:
                cur = c.execute("INSERT INTO chunks (kind,text,norm,tags,created_at,updated_at) VALUES ('fact',?,?,?,?,?)",
                                (ch.text, normalize(ch.text), " ".join(unique_keywords(ch.text, 6)), now, now))
                c.execute("INSERT INTO chunks_fts(rowid,text,tags) VALUES (?,?,?)", (cur.lastrowid, ch.text, ""))
        res = {}
        for name, rule in SETTINGS.items():
            m.evidence_rule = rule
            m._count_cache.clear()
            by, d_tokens, e_tokens, e_rec = {}, [], [], []
            for q in gym.queries:
                r = m.retrieve(q.text, log=False)
                got = {c["id"] for c in r["chunks"]}
                if q.kind == "D":
                    d_tokens.append(r["tokens"])
                else:
                    by.setdefault(q.group, []).append(sum((i + 1) in got for i in q.needed) / len(q.needed))
            for text, needed in shorts:
                r = m.retrieve(text, log=False)
                got = {c["id"] for c in r["chunks"]}
                e_tokens.append(r["tokens"])
                e_rec.append(sum((i + 1) in got for i in needed) / len(needed))
            res[name] = {"tokens_D": statistics.mean(d_tokens), "macro_recall_ABC": statistics.mean(statistics.mean(v) for v in by.values()),
                         "recall_E": statistics.mean(e_rec), "tokens_E": statistics.mean(e_tokens)}
            print(name, json.dumps(res[name]), flush=True)
    base = res["baseline"]
    verdicts = {}
    for name in list(SETTINGS)[1:]:
        r = res[name]
        checks = {"D_tokens_down_80pct": r["tokens_D"] <= 0.2 * base["tokens_D"],
                  "ABC_recall_within_0.01": r["macro_recall_ABC"] >= base["macro_recall_ABC"] - 0.01,
                  "E_recall_within_0.05": r["recall_E"] >= base["recall_E"] - 0.05}
        verdicts[name] = {"checks": checks, "pass": all(checks.values())}
    passing = [n for n, v in verdicts.items() if v["pass"]]
    adopted = min(passing, key=lambda n: res[n]["tokens_D"] + res[n]["tokens_E"]) if passing else None
    rep = {"results": res, "verdicts": verdicts, "adopted": adopted}
    (HERE / "results.json").write_text(json.dumps(rep, indent=1))
    L = ["# E4 results (loading nothing for vague questions)", "",
         f"Generated by `run.py`. Rules in `PROTOCOL.md` were fixed before the rule was implemented. Synthetic text, N = {N_TOPICS * 50:,}, seed {SEED}.", "",
         f"## Verdict: **{'ADOPT ' + adopted if adopted else 'NOT ADOPTED'}**", ""]
    for n, v in verdicts.items():
        L.append(f"- setting {n}: " + ", ".join(f"{'pass' if ok else 'FAIL'} {k}" for k, ok in v["checks"].items()))
    L += ["", "| Setting | Tokens on vague (D) | Recall A/B/C | Recall short (E) | Tokens on short (E) |", "|---|---|---|---|---|"]
    for n, r in res.items():
        L.append(f"| {n} | {r['tokens_D']:.0f} | {r['macro_recall_ABC']:.3f} | {r['recall_E']:.3f} | {r['tokens_E']:.0f} |")
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
